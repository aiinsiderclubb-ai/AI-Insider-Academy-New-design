function agentPack(role: string, rules: string[], tools: string[]): DownloadFile[] {
  return [
    file("Системный промпт", "System prompt", "system-prompt.md", "text/markdown", [
      ["Роль", role],
      ["Правила", rules.map((rule, index) => `${index + 1}. ${rule}`).join("\n")],
      ["Инструменты", tools.map((tool) => `- ${tool}`).join("\n")],
      ["Если не знает", "Скажи, что не нашёл это в инструкции, и передай диалог человеку. Не выдумывай цену, срок и наличие."],
    ]),
    jsonFile("Схемы инструментов", "Tool schemas", "tools.json", {
      tools: tools.map((tool) => ({ name: tool, input: { note: "string" }, output: { ok: "boolean" } })),
    }),
  ];
}

