/* --------------------------------- n8n ------------------------------------ */

function workflow(name: string, steps: string[]) {
  return {
    name,
    nodes: steps.map((step, index) => ({
      id: String(index + 1),
      name: step,
      type: index === 0 ? "n8n-nodes-base.webhook" : "n8n-nodes-base.set",
      typeVersion: 1,
      position: [240 + index * 220, 300],
      parameters: index === 0 ? { path: name.toLowerCase().replace(/\s+/g, "-"), httpMethod: "POST" } : { keepOnlySet: false },
    })),
    connections: Object.fromEntries(
      steps.slice(0, -1).map((step, index) => [step, { main: [[{ node: steps[index + 1], type: "main", index: 0 }]] }]),
    ),
    notes: "Импортируйте JSON в n8n и подставьте свои credentials. Секретов в файле нет.",
  };
}

