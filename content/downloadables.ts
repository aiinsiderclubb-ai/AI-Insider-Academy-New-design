/**
 * Downloadable starter files for every marketplace product.
 * The full archive still ships after purchase; these are the working files
 * a buyer can open immediately from the product page.
 */

export interface DownloadFile {
  filename: string;
  labelRu: string;
  labelEn: string;
  mime: string;
  body: string;
}

type Block = readonly [string, string];

function markdown(blocks: Block[]): string {
  return `${blocks.map(([heading, body]) => `## ${heading}\n\n${body.trim()}`).join("\n\n")}\n`;
}

function file(labelRu: string, labelEn: string, filename: string, mime: string, blocks: Block[]): DownloadFile {
  return { filename, labelRu, labelEn, mime, body: markdown(blocks) };
}

function jsonFile(labelRu: string, labelEn: string, filename: string, value: unknown): DownloadFile {
  return {
    filename,
    labelRu,
    labelEn,
    mime: "application/json",
    body: `${JSON.stringify(value, null, 2)}\n`,
  };
}

const PACKS: Record<string, DownloadFile[]> = {};

function add(slug: string, files: DownloadFile[]) {
  PACKS[slug] = files;
}

