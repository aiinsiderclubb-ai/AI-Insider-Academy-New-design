function mcpPack(title: string, servers: { name: string; does: string }[]): DownloadFile[] {
  return [
    file("Как подключить", "How to connect", "readme.md", "text/markdown", [
      ["Набор", title],
      ["Серверы", servers.map((server) => `- ${server.name}: ${server.does}`).join("\n")],
      ["Секреты", "Ключи кладите в переменные окружения. В репозиторий и в чат их не копируйте."],
      ["Проверка", "Спросите агента о тестовой записи, которую создали сами. Если он отвечает без вызова инструмента, конфиг не подключился."],
    ]),
    jsonFile("Конфиг MCP", "MCP config", "mcp.json", {
      mcpServers: Object.fromEntries(servers.map((server) => [server.name, { command: "npx", args: [`mcp-${server.name}`], env: { TOKEN: "" } }])),
    }),
  ];
}

